import { Pool } from 'pg'
import { AsyncLocalStorage } from 'node:async_hooks'
import { readFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const connectionString = process.env.DATABASE_URL

if (!connectionString) {
  throw new Error('DATABASE_URL is required. PostgreSQL is the active database engine for this project.')
}

const pool = new Pool({
  connectionString,
  ssl: process.env.DATABASE_SSL === 'true' ? { rejectUnauthorized: false } : undefined,
  max: 10,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 10000,
})
const transactionStorage = new AsyncLocalStorage()

const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..')

function postgresSchema(sql) {
  return sql
    .replace(/^PRAGMA[^;]+;\s*/i, '')
    .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/INSERT OR IGNORE INTO ([\s\S]*?);/gi, 'INSERT INTO $1 ON CONFLICT DO NOTHING;')
}

export const databaseReady = readFile(join(rootDir, 'database', 'schema.sql'), 'utf8')
  .then((schema) => pool.query(postgresSchema(schema)))

function normalizeSql(sql, params) {
  const values = Array.isArray(params) ? params : [params]
  const normalizedValues = values.flatMap((value) => Array.isArray(value) ? value : [value])

  let index = 1
  let normalized = sql

  if (normalizedValues.length === 1 && normalizedValues[0] && typeof normalizedValues[0] === 'object' && !Array.isArray(normalizedValues[0])) {
    const entries = normalizedValues[0]
    const names = []
    normalized = normalized.replace(/@([A-Za-z_][A-Za-z0-9_]*)/g, (_, name) => {
      names.push(name)
      return `$${names.length}`
    })
    return { text: normalized, values: names.map((name) => entries[name]) }
  }

  normalized = normalized.replace(/\?/g, () => `$${index++}`)
  normalized = normalized
    .replace(/INSERT OR IGNORE INTO/gi, 'INSERT INTO')
    .replace(/(VALUES\s*\([\s\S]*?\))\s*$/i, '$1 ON CONFLICT DO NOTHING')
    .replace(/date\('now'\)/gi, 'CURRENT_DATE')
    .replace(/datetime\(['"]now['"]\)/gi, 'NOW()')
    .replace(/datetime\(([^)]+)\)/gi, '$1')
    .replace(/GROUP_CONCAT\(DISTINCT\s+([^\)]+)\)/gi, "STRING_AGG(DISTINCT $1, ',')")

  if (/^\s*INSERT\s/i.test(normalized) && !/\bRETURNING\b/i.test(normalized)) {
    normalized = `${normalized.trimEnd()} RETURNING id`
  }

  return { text: normalized, values: normalizedValues }
}

class PreparedStatement {
  constructor(sql) {
    this.sql = sql
  }

  async _query(method, rawParams = []) {
    await databaseReady
    const { text, values } = normalizeSql(this.sql, rawParams)
    const client = transactionStorage.getStore()
    const result = await (client ?? pool).query(text, values)

    if (method === 'get') return result.rows[0] ?? undefined
    if (method === 'all') return result.rows
    if (method === 'run') {
      const row = result.rows[0]
      const lastInsertRowid = row && Object.prototype.hasOwnProperty.call(row, 'id') ? row.id : null
      return { changes: result.rowCount ?? 0, lastInsertRowid }
    }

    return result
  }

  get(...params) {
    return this._query('get', params)
  }

  all(...params) {
    return this._query('all', params)
  }

  run(...params) {
    return this._query('run', params)
  }
}

export const db = {
  prepare(sql) {
    return new PreparedStatement(sql)
  },
  exec(sql) {
    return databaseReady.then(() => pool.query(sql))
  },
  transaction(callback) {
    return async () => {
      const client = await pool.connect()
      try {
        await client.query('BEGIN')
        const result = await transactionStorage.run(client, () => callback())
        await client.query('COMMIT')
        return result
      } catch (error) {
        await client.query('ROLLBACK')
        throw error
      } finally {
        client.release()
      }
    }
  },
}

export function toPublicUser(user) {
  return {
    id: user.id,
    name: user.name,
    email: user.email,
    role: user.role,
  }
}
